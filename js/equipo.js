// Competencia con armas por clase (SRD 5.2.1). Devuelve si una clase sabe usar un arma.
export function competenteCon(clase, arma) {
  const c = String(clase || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  if (!arma) return false;
  if (arma.cat === 'sencilla') return true;
  if (/barbar|explorador|guerrer|paladin/.test(c)) return true; // también en femenino: guerrera, bárbara…
  if (/monj/.test(c)) return arma.ligera;
  if (/picar/.test(c)) return arma.ligera || arma.sutil;
  return false;
}

